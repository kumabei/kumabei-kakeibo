// Builds js/icon-paths.js from Tabler Icons (outline). Run from the app folder: node tools/make_icons.mjs
// Needs network access (cdn.jsdelivr.net). Keep NAMES in step with PICKER_ICONS and UI_ICONS in js/icons.js
// (tests/icons.test.js checks it).
import { writeFileSync } from 'node:fs';

const VERSION = '3.19.0';
const BASE = `https://cdn.jsdelivr.net/npm/@tabler/icons@${VERSION}`;
const NAMES = [
  // the initial categories e01-e21 (js/icons.js DEFAULT_ICONS)
  'tools-kitchen-2', 'bowl-chopsticks', 'cookie', 'bottle', 'shirt', 'mood-kid', 'book', 'glass-full', 'car',
  'gas-station', 'bus', 'ticket', 'first-aid-kit', 'device-mobile', 'bulb', 'home', 'armchair', 'wallet',
  'receipt', 'dots', 'shield-check',
  // more to choose from in the settings
  'cash', 'briefcase', 'gift', 'coin', 'pig-money', 'shopping-cart', 'basket', 'coffee', 'pizza', 'pill',
  'dental', 'scissors', 'paw', 'plane', 'ball-football', 'heart', 'tools', 'device-tv', 'wifi', 'droplet',
  'flame', 'building-bank', 'baby-bottle', 'bike', 'music',
  // used by the screens
  'check', 'x', 'calendar', 'pencil', 'backspace',
];

async function text(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

const license = await text(`${BASE}/LICENSE`);
const paths = {};
for (const name of NAMES) {
  const svg = await text(`${BASE}/icons/outline/${name}.svg`);
  paths[name] = [...svg.replace(/\s*\n\s*/g, ' ').matchAll(/<path [^>]*\/>/g)]
    .map(m => m[0].replace(/\s+\/>$/, '/>'))
    .filter(p => !p.includes('d="M0 0h24v24H0z"')) // Tabler's invisible bounding box
    .join('');
}

const out = [
  '// Generated by tools/make_icons.mjs. Do not edit by hand.',
  `// Line icons from Tabler Icons ${VERSION} (https://tabler.io/icons), outline style.`,
  '/*',
  license.trim(),
  '*/',
  'export const ICON_PATHS = {',
  ...NAMES.map(n => `  ${JSON.stringify(n)}: ${JSON.stringify(paths[n])},`),
  '};',
  '',
].join('\n');
writeFileSync(new URL('../js/icon-paths.js', import.meta.url), out);
console.log(`${NAMES.length} icons written`);
